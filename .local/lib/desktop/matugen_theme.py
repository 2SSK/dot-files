#!/usr/bin/env python3
"""A theme family made from a picture by matugen (Material You), in the same form as themes/*.toml.

usage: matugen_theme.py <image> <out.toml>

Both modes from one run. The interface takes Material's roles; the terminal's eight hues are the
usual ones (red is still red) blended toward the picture's colour by matugen, a little brighter for
the bright half. Standard library only; matugen does the colour science.
"""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

# the terminal hues before blending (One Dark's: clear, and not too loud)
HUES = {"red": "#e06c75", "green": "#98c379", "yellow": "#e5c07b", "blue": "#61afef",
        "magenta": "#c678dd", "cyan": "#56b6c2"}


def matugen(image):
    config = "[templates]\n\n[config.custom_colors]\n" + "".join(
        f'{name} = {{ color = "{hex_}", blend = true }}\n' for name, hex_ in HUES.items())
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "config.toml").write_text(config)
        # --prefer: a picture with several candidate colours would otherwise ask on a terminal
        result = subprocess.run(["matugen", "image", str(image), "-c", "config.toml", "--dry-run", "--quiet",
                                 "--json", "hex", "--prefer", "saturation"],
                                cwd=tmp, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        raise SystemExit(f"matugen failed: {result.stderr.strip() or result.returncode}")
    colours = json.loads(result.stdout)["colors"]
    return {mode: {k: v[mode]["color"] for k, v in colours.items()} for mode in ("dark", "light")}


def mix(a, b, amount):
    """a moved toward b by amount (0..1), as #rrggbb."""
    pa = [int(a[i:i + 2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * amount):02x}" for x, y in zip(pa, pb))


def roles(c, dark):
    ui = {
        "bg": c["surface"],
        "bg_alt": c["surface_container_lowest"] if dark else c["surface_container_high"],
        "surface": c["surface_container_high"] if dark else c["surface_container_highest"],
        "overlay": c["outline_variant"],
        "fg": c["on_surface"],
        "fg_muted": c["outline"],
        "primary": c["primary"],
        "on_primary": c["on_primary"],
        "secondary": c["tertiary"],
        "accent": c["secondary"],
        "success": c["green"],
        "warning": c["yellow"],
        "error": c["error"],
        "border": c["outline_variant"],
        "border_active": c["primary"],
        "selection": c["primary_container"],
    }
    toward = "#ffffff" if dark else "#000000"
    normal = [c["surface_container_lowest"] if dark else c["on_surface"], c["red"], c["green"], c["yellow"],
              c["blue"], c["magenta"], c["cyan"], c["on_surface_variant"] if dark else c["outline_variant"]]
    bright = [c["outline"]] + [mix(x, toward, 0.2) for x in normal[1:7]] + [c["on_surface"] if dark else c["surface_container_highest"]]
    ansi = {f"c{i}": colour for i, colour in enumerate(normal + bright)}
    return ui, ansi


def toml(table):
    return "".join(f'{k} = "{v}"\n' for k, v in table.items())


def main(argv):
    if len(argv) != 2:
        print(__doc__.split("\n\n")[1], file=sys.stderr)
        return 2
    image, out = Path(argv[0]), Path(argv[1])
    colours = matugen(image)
    text = ['# Generated by matugen_theme.py from the wallpaper; regenerated when it changes.\n\n',
            '[meta]\nfamily = "matugen"\nname = "Matugen"\n',
            f'source = "{image.name}"\nlicense = "-"\n']
    for mode in ("dark", "light"):
        ui, ansi = roles(colours[mode], mode == "dark")
        text += [f"\n[{mode}.ui]\n", toml(ui), f"\n[{mode}.ansi]\n", toml(ansi)]
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = out.with_suffix(".tmp")
    tmp.write_text("".join(text))
    tmp.replace(out)  # readers see the old palette or the new one
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
